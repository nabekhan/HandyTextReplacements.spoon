local Engine = {}

local VALID_CAPITALIZATION = {
    none = true,
    force_uppercase = true,
    force_lowercase = true,
}

local UNICODE_PUNCTUATION = {
    ["«"] = true,
    ["»"] = true,
    ["—"] = true,
    ["–"] = true,
    ["…"] = true,
    ["’"] = true,
    ["‘"] = true,
    ["“"] = true,
    ["”"] = true,
}

local UNICODE_WHITESPACE = {
    ["\u{00a0}"] = true,
    ["\u{1680}"] = true,
    ["\u{2000}"] = true,
    ["\u{2001}"] = true,
    ["\u{2002}"] = true,
    ["\u{2003}"] = true,
    ["\u{2004}"] = true,
    ["\u{2005}"] = true,
    ["\u{2006}"] = true,
    ["\u{2007}"] = true,
    ["\u{2008}"] = true,
    ["\u{2009}"] = true,
    ["\u{200a}"] = true,
    ["\u{2028}"] = true,
    ["\u{2029}"] = true,
    ["\u{202f}"] = true,
    ["\u{205f}"] = true,
    ["\u{3000}"] = true,
}

-- Structural delimiters generated by replacements remain wrapped in
-- noncharacters until every rule has run. Later punctuation-trimming rules
-- therefore cannot mistake ], ), or ” for punctuation added by Whisper.
local PROTECTION_START = utf8.char(0xfdd0)
local PROTECTION_END = utf8.char(0xfdd1)
local PROTECTED_DELIMITERS = {
    "(", ")", "[", "]", "{", "}", "“", "”", "‘", "’", "«", "»",
}

local function isProtectionMarker(char)
    return char == PROTECTION_START or char == PROTECTION_END
end

local function replacePlain(text, needle, replacement)
    local result = {}
    local position = 1

    while true do
        local startByte, endByte = text:find(needle, position, true)
        if not startByte then
            result[#result + 1] = text:sub(position)
            break
        end

        result[#result + 1] = text:sub(position, startByte - 1)
        result[#result + 1] = replacement
        position = endByte + 1
    end

    return table.concat(result)
end

local function protectReplacement(text)
    local result = text
    for _, delimiter in ipairs(PROTECTED_DELIMITERS) do
        result = replacePlain(
            result,
            delimiter,
            PROTECTION_START .. delimiter .. PROTECTION_END
        )
    end
    return result
end

local function removeProtectionMarkers(text)
    return (text:gsub(PROTECTION_START, ""):gsub(PROTECTION_END, ""))
end

local function characterRecords(text)
    local records = {}
    local valid = pcall(function()
        for byteIndex, codepoint in utf8.codes(text) do
            local char = utf8.char(codepoint)
            records[#records + 1] = {
                char = char,
                codepoint = codepoint,
                startByte = byteIndex,
                endByte = byteIndex + #char - 1,
            }
        end
    end)

    if valid then
        return records
    end

    -- Clipboard strings should be UTF-8, but preserve invalid input rather
    -- than failing a dictation if another application supplied raw bytes.
    records = {}
    for index = 1, #text do
        records[#records + 1] = {
            char = text:sub(index, index),
            codepoint = text:byte(index),
            startByte = index,
            endByte = index,
        }
    end
    return records
end

local lowerByChar = {}
local upperByChar = {}
local accentBase = {}

for byte = string.byte("A"), string.byte("Z") do
    local upper = string.char(byte)
    local lower = string.char(byte + 32)
    lowerByChar[upper] = lower
    lowerByChar[lower] = lower
    upperByChar[upper] = upper
    upperByChar[lower] = upper
end

local function registerAccentGroup(upperBase, lowerBase, uppers, lowers)
    local upperChars = characterRecords(uppers)
    local lowerChars = characterRecords(lowers)

    for index, upperRecord in ipairs(upperChars) do
        local lowerRecord = lowerChars[index]
        if lowerRecord then
            local upper = upperRecord.char
            local lower = lowerRecord.char
            lowerByChar[upper] = lower
            lowerByChar[lower] = lower
            upperByChar[upper] = upper
            upperByChar[lower] = upper
            accentBase[upper] = upperBase
            accentBase[lower] = lowerBase
        end
    end
end

